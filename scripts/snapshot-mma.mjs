#!/usr/bin/env node
// Snapshot octopus-mma's techniques into health, from mma's `main` branch (git show), never from
// whatever branch mma has checked out and never by changing that repo.
//
//   node scripts/snapshot-mma.mjs            write public/poses/mma/*.json and lib/mma-moves.json
//   node scripts/snapshot-mma.mjs --check    exit 1 if the committed snapshot differs from mma main
//
// What is copied: the pose JSON (byte for byte) and, from each technique's markdown, the title,
// discipline, level, type, summary, "Steps" and "Key Points". What is NOT copied: poses that do not
// pass health's own validator. Poses with a second ("partner") figure ARE copied: health's engine
// draws them. Skipped moves are listed in the catalogue with the reason, never dropped silently.
//
// mma is a PUBLIC repo with no LICENSE file (checked 2026-11-07): the content was written inside
// this estate, so copying it between two estate repos is the owner's own material. The owner
// should still confirm before it is offered to paying clients. See SESSIONS.md.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const MMA = process.env.MMA_REPO || path.join(root, '..', 'octopus-mma');
const SF = require(path.join(root, 'public', 'stick-figure.js'));
const git = (...a) => execFileSync('git', ['-C', MMA, ...a], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

export function parseFrontmatter(raw) {
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(raw);
  if (!m) return { data: {}, body: raw };
  const data = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i < 1) continue;
    const k = line.slice(0, i).trim();
    const v = line.slice(i + 1).trim();
    try { data[k] = JSON.parse(v); } catch { data[k] = v.replace(/^["']|["']$/g, ''); }
  }
  return { data, body: m[2] };
}

export function section(body, heading) {
  const m = new RegExp('^## ' + heading + '\\s*\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))', 'm').exec(body);
  if (!m) return [];
  return m[1].split('\n').map((l) => l.replace(/^\s*(?:\d+\.|-)\s+/, '').trim()).filter(Boolean);
}

// The steps of a technique. Most files have a "## Steps" section; the BJJ ones are named after the
// position instead ("## Closed Guard", "## Getting to Mount"), so fall back to the first section
// that holds a numbered list, ignoring the sections that are never steps.
export function stepsOf(body) {
  const direct = section(body, 'Steps');
  if (direct.length) return { steps: direct };
  const skip = /^(key points|common mistakes|drills|variations|safety|related|history)/i;
  for (const m of body.matchAll(/^## (.+)$/gm)) {
    if (skip.test(m[1].trim())) continue;
    const sec = new RegExp('^## ' + m[1].replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))', 'm').exec(body);
    const lines = sec ? sec[1].split('\n').filter((l) => /^\s*\d+\.\s/.test(l)) : [];
    if (lines.length >= 2) return { steps: lines.map((l) => l.replace(/^\s*\d+\.\s+/, '').trim()), stepsTitle: m[1].trim() };
  }
  return { steps: [] };
}

export function build() {
  const sha = git('rev-parse', 'main').trim();
  const files = git('ls-tree', '-r', '--name-only', 'main', 'content').split('\n').filter(Boolean);
  const mds = files.filter((f) => f.endsWith('.md'));
  const moves = [], skipped = [], poseFiles = {};
  for (const md of mds) {
    const [, discipline, level, file] = md.split('/');
    const slug = file.replace(/\.md$/, '');
    const { data, body } = parseFrontmatter(git('show', 'main:' + md));
    const poseRel = md.replace(/\.md$/, '.poses.json');
    const id = `${discipline}-${slug}`;
    if (!files.includes(poseRel)) { skipped.push({ id, reason: 'no pose file' }); continue; }
    const rawPose = git('show', 'main:' + poseRel);
    const pose = JSON.parse(rawPose);
    const errs = SF.validate(pose);
    if (errs.length) { skipped.push({ id, reason: 'fails health\'s pose validator: ' + errs[0] }); continue; }
    if (poseFiles[id]) throw new Error('duplicate move id ' + id);
    poseFiles[id] = rawPose;
    moves.push({
      id, poseKey: 'mma/' + id, title: data.title || slug, discipline, level,
      techniqueType: data.techniqueType || null, difficulty: data.difficulty || null,
      nativeName: data.nativeName || null, summary: data.summary || '',
      ...stepsOf(body), keyPoints: section(body, 'Key Points'),
    });
  }
  moves.sort((a, b) => a.id.localeCompare(b.id));
  skipped.sort((a, b) => a.id.localeCompare(b.id));
  const catalogue = {
    _about: 'Snapshot of octopus-mma technique text and pose JSON. Generated by scripts/snapshot-mma.mjs; do not hand-edit. A fix in mma reaches health only by re-running the script.',
    source: 'octopus-mma main', sourceCommit: sha, moves, skipped,
  };
  return { catalogue, poseFiles };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { catalogue, poseFiles } = build();
  const outDir = path.join(root, 'public', 'poses', 'mma');
  const catPath = path.join(root, 'lib', 'mma-moves.json');
  const catText = JSON.stringify(catalogue, null, 2) + '\n';
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(catPath) ? JSON.parse(fs.readFileSync(catPath, 'utf8')) : null;
    const same = have && JSON.stringify(have.moves) === JSON.stringify(catalogue.moves) &&
      Object.entries(poseFiles).every(([id, t]) => fs.existsSync(path.join(outDir, id + '.json')) && fs.readFileSync(path.join(outDir, id + '.json'), 'utf8') === t);
    console.log(same ? 'mma snapshot is current with mma main ' + catalogue.sourceCommit.slice(0, 7) : 'mma snapshot DIFFERS from mma main ' + catalogue.sourceCommit.slice(0, 7) + ': run node scripts/snapshot-mma.mjs');
    process.exit(same ? 0 : 1);
  }
  fs.mkdirSync(outDir, { recursive: true });
  for (const f of fs.readdirSync(outDir)) if (f.endsWith('.json')) fs.rmSync(path.join(outDir, f));
  for (const [id, t] of Object.entries(poseFiles)) fs.writeFileSync(path.join(outDir, id + '.json'), t);
  fs.writeFileSync(catPath, catText);
  console.log(`wrote ${catalogue.moves.length} moves, skipped ${catalogue.skipped.length} (mma main ${catalogue.sourceCommit.slice(0, 7)})`);
  for (const s of catalogue.skipped) console.log('  skipped', s.id, '-', s.reason);
}
