#!/usr/bin/env node
// Generates docs/exercise-pose-table.md: every library exercise and mobility item -> the stick-figure
// pose it resolves to, and whether that came from a name rule or the category fallback.
//
//   node scripts/pose-table.mjs           rewrite the committed table
//   node scripts/pose-table.mjs --check   exit 1 if the committed table is stale
//
// test/exercise-guards.test.js fails when the committed file is stale, so any change to a pose rule,
// a category fallback or an exercise name shows up in the PR diff of this file.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { inventory } = require('./exercise-inventory.cjs');
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'exercise-pose-table.md');

export function buildTable() {
  const rows = inventory();
  const cell = s => String(s == null || s === '' ? '-' : s).replace(/\|/g, '\\|');
  const lines = [
    '# Exercise to figure table',
    '',
    'GENERATED by `node scripts/pose-table.mjs` - do not edit by hand. `test/exercise-guards.test.js` fails when this file is stale.',
    'A change to `public/pose-map.js`, a category fallback or an exercise name shows up here, so a reviewer sees exactly which exercises changed figure.',
    '',
    '"how": `rule` = a name rule matched; `category fallback` = no rule, the category figure is shown; `null rule -> category fallback` = a rule says "no figure yet" but the category figure is still shown; `none (martial: no figure)` = the card says "No diagram yet".',
    '',
    `${rows.filter(r => r.source === 'library').length} library exercises, ${rows.filter(r => r.source === 'mobility').length} mobility items.`,
    '',
    '| source | id | name | category | figure | how |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of rows) lines.push(`| ${cell(r.source)} | ${cell(r.id)} | ${cell(r.name)} | ${cell(r.category)} | ${cell(r.pose)} | ${cell(r.how)} |`);
  return lines.join('\n') + '\n';
}

export const TABLE_PATH = OUT;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildTable();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('docs/exercise-pose-table.md is stale: run node scripts/pose-table.mjs'); process.exit(1); }
    console.log('pose table is current');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
  }
}
